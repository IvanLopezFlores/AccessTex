// 🧠 Traducción automática de errores comunes de LaTeX
function traducirErrorLatex(error) {
  if (!error || typeof error !== "string") return "";

  const erroresConocidos = {
    "Undefined control sequence": {
      es: "Comando no reconocido (posible error tipográfico o falta de paquete)",
      en: "Undefined command (possible typo or missing package)"
    },
    "Missing \\$ inserted": {
      es: "Falta signo de dólar ($) para iniciar o cerrar fórmula en modo matemático",
      en: "Missing dollar sign ($) to start or end math mode"
    },
    "Extra \\} or forgotten \\\\end": {
      es: "Llave de cierre extra o falta un \\end",
      en: "Extra closing brace or missing \\end"
    },
    "Missing \\\\begin": {
      es: "Falta un entorno \\begin",
      en: "Missing \\begin environment"
    },
    "Argument of .* has an extra \\}": {
      es: "Argumento con llave de cierre extra",
      en: "Argument has an extra closing brace"
    },
    "Runaway argument": {
      es: "Argumento extendido más de lo esperado (Runaway argument)",
      en: "Runaway argument: command argument extends too far"
    },
    "Package .* Error:": {
      es: "Error generado por un paquete LaTeX",
      en: "Error generated by a LaTeX package"
    },
    "Paragraph ended before .* was complete": {
      es: "Párrafo terminado antes de que se completara un entorno",
      en: "Paragraph ended before an environment was complete"
    },
    "Invalid UTF-8 byte sequence": {
      es: "Secuencia UTF-8 inválida (verifica codificación o caracteres especiales)",
      en: "Invalid UTF-8 byte sequence (check encoding or special characters)"
    }
  };

  for (const patron in erroresConocidos) {
    const regex = new RegExp(patron, "i");
    if (regex.test(error)) {
      return erroresConocidos[patron][idioma] || error;
    }
  }

  return error;
}

function compilarLatex() {
  const latex = window.editor.getValue();
  const errores = document.getElementById("errores");
  const pdf = document.getElementById("descargarPDF");
  const tex = document.getElementById("descargarTEX");
if (!latex.trim()) {
  errores.value = t("documento_vacio");

  pdf.style.display = "none";
  pdf.setAttribute("aria-hidden", "true");
  pdf.setAttribute("tabindex", "-1");

  tex.style.display = "none";
  tex.setAttribute("aria-hidden", "true");
  tex.setAttribute("tabindex", "-1");

  ultimaLineaError = null;
  speak(t("documento_vacio"));
  return;
}


  fetch("/compilar", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ latex })
  })
  .then(res => res.json())
  .then(data => {
    const errores = document.getElementById("errores");
    const pdf = document.getElementById("descargarPDF");
    const tex = document.getElementById("descargarTEX");

    const rawError = data.errores || "";
    const latexErrorMsg = rawError.replace(/^!\s*/, ""); // quitar "!" inicial
    const baseError = traducirErrorLatex(latexErrorMsg);

    const yaIncluyeLinea = data.linea_num && baseError.includes(data.linea_num.toString());

    const lineaInfo = (!yaIncluyeLinea && data.linea_num)
      ? `${t("error_en_linea", data.linea_num)}${data.preciso === false ? ` ${t("ubicacion_inexacta")}` : ""}`
      : "";

    const mensajeCompleto = data.errores
      ? `${baseError}. ${lineaInfo}. ${t("contexto")}: ${data.contexto || t("no_disponible")}`
      : t("compilacion_exitosa");

    errores.value = mensajeCompleto;

    if (data.pdf) {
      pdf.href = "/pdf";
      pdf.style.display = "inline";
      pdf.setAttribute("aria-hidden", "false");
      pdf.setAttribute("tabindex", "0");

      tex.href = "/documento.tex";
      tex.style.display = "inline";
      tex.setAttribute("aria-hidden", "false");
      tex.setAttribute("tabindex", "0");

      speak(t("compilacion_exitosa"));
      ultimaLineaError = null;
    } else {
      pdf.style.display = "none";
      pdf.setAttribute("aria-hidden", "true");
      pdf.setAttribute("tabindex", "-1");

      tex.style.display = "none";
      tex.setAttribute("aria-hidden", "true");
      tex.setAttribute("tabindex", "-1");

      const linea = data.linea_num;
      ultimaLineaError = linea ? parseInt(linea) : null;

      if (ultimaLineaError) {
        speakEncadenado(mensajeCompleto, t("ir_a_linea_error"));
      } else {
        speak(mensajeCompleto);
      }
    }
  })
  .catch(() => {
    document.getElementById("errores").value = t("error_servidor");
    speak(t("error_servidor"));
  });
}
